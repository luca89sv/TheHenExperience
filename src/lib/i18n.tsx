type Lang = "pl" | "en";
type TranslationKey = keyof typeof translations.en;

interface LanguageContextType {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextType | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("pl");
  const [langResolved, setLangResolved] = useState(false);

  useEffect(() => {
    const saved = localStorage.getItem("lang");
    if (saved === "en" || saved === "pl") setLangState(saved);
    setLangResolved(true);
  }, []);

  // Reveal content AFTER React has re-rendered with the correct language
  useEffect(() => {
    if (langResolved) {
      requestAnimationFrame(() => {
        document.body.classList.add("lang-ready");
      });
    }
  }, [langResolved, lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem("lang", l);
  }, []);

  const t = useCallback(
    (key: string): string => {
      const dict = translations[lang] as Record<string, string>;
      return dict[key] ?? key;
    },
    [lang]
  );

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return ctx;
}

/** Inline translation component. Supports HTML in translation values. */
export function T({ k }: { k: string }) {
  const { t } = useLanguage();
  const value = t(k);
  if (value.includes("<")) {
    return <span dangerouslySetInnerHTML={{ __html: value }} />;
  }
  return <>{value}</>;
}
